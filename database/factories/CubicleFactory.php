<?php

namespace Database\Factories;

use App\Enums\CubicleStatus;
use App\Enums\DayOfWeek;
use App\Enums\DentalSpecialty;
use App\Models\Branch;
use App\Models\Cubicle;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends Factory<Cubicle>
 */
class CubicleFactory extends Factory
{
    protected $model = Cubicle::class;

    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'branch_id' => Branch::factory(),
            'name' => 'Cubículo '.fake()->numerify('#').' - General',
            'code' => null, // Will be generated by CubicleObserver
            'specialty_types' => [DentalSpecialty::General->value],
            'specialty_schedules' => null,
            'status' => CubicleStatus::Active,
        ];
    }

    public function maintenance(): static
    {
        return $this->state(fn (array $attributes) => [
            'status' => CubicleStatus::Maintenance,
        ]);
    }

    public function inactive(): static
    {
        return $this->state(fn (array $attributes) => [
            'status' => CubicleStatus::Inactive,
        ]);
    }

    public function withSpecialtySchedule(DayOfWeek $day, DentalSpecialty $specialty, string $startTime = '08:00', string $endTime = '18:00'): static
    {
        return $this->state(function (array $attributes) use ($day, $specialty, $startTime, $endTime) {
            $specialtyTypes = $attributes['specialty_types'] ?? [DentalSpecialty::General->value];
            if (! in_array($specialty->value, $specialtyTypes, true)) {
                $specialtyTypes[] = $specialty->value;
            }

            $schedules = $attributes['specialty_schedules'] ?? [];
            $schedules[] = [
                'day' => $day->value,
                'specialty' => $specialty->value,
                'start_time' => $startTime,
                'end_time' => $endTime,
            ];

            return [
                'specialty_types' => $specialtyTypes,
                'specialty_schedules' => $schedules,
            ];
        });
    }
}
